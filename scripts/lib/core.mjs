// The C target for rekta-core: tokens, icons and fonts as C source, from the same sources as the web. The files are
// committed (core/src/rk_tokens.h, rk_icons.h, rk_fonts.h), so building the C library needs no Node; --check fails
// when they are out of date. The order of every table follows an enum in core/include/rekta.h.

import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from './color.mjs';

const HEAD = (what) => `/* ${what}. Generated by scripts/build.mjs; do not edit. */\n`;
const f = (n) => { const s = (+n.toFixed(4)).toString(); return /[.e]/.test(s) ? `${s}f` : `${s}.0f`; };
const C = (name) => name.toUpperCase().replace(/[^A-Z0-9]+/g, '_');

// rk_role, after RK_ROLE_NONE.
const ROLES = ['bg', 'surface', 'surface-2', 'text-primary', 'text-contrast-low', 'text-contrast-medium', 'text-contrast-high',
  'accent', 'on-accent',
  'status-info-full', 'status-info-soft', 'status-info-tile', 'status-success-full', 'status-success-soft', 'status-success-tile',
  'status-warning-full', 'status-warning-soft', 'status-warning-tile', 'status-error-full', 'status-error-soft', 'status-error-tile',
  'focus', 'hover', 'disabled', 'shading', 'glass'];
// rk_metric: [group, key]; the last three come from the density.
const METRICS = [['spacing', 'space-xs'], ['spacing', 'space-s'], ['spacing', 'space-m'], ['spacing', 'space-l'], ['spacing', 'space-xl'],
  ['radius', 'radius-s'], ['radius', 'radius-m'], ['radius', 'radius-l'], ['radius', 'radius-tile'],
  ['size', 'tile-unit'], ['size', 'appbar-height'], ['size', 'touch-target'], ['size', 'pane-min'],
  ['density', 'control-height'], ['density', 'row-height'], ['density', 'control-padding']];
// rk_duration; motion durations first (zero under reduced motion), then wall-clock timings.
const DURATIONS = [['motion', 'duration-press'], ['motion', 'duration-short'], ['motion', 'duration-moderate'], ['motion', 'duration-long'],
  ['motion', 'duration-stagger'], ['motion', 'duration-float'], ['motion', 'duration-pivot-glide'], ['motion', 'duration-pivot-size'],
  ['timing', 'duration-toast'], ['timing', 'duration-tap-delay'], ['timing', 'duration-long-press'], ['timing', 'duration-tip-delay']];
const MOTION_COUNT = 8;

const rgba = (css) => {
  const { r, g, b, a } = parse(css);
  const h = (v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0');
  return `0x${h(r)}${h(g)}${h(b)}${h(a)}u`;
};

export function coreTokens(json) {
  const problems = [];
  const themes = ['light', 'dark'].map((t) => {
    const theme = json.themes[t];
    for (const k of Object.keys(theme)) if (!ROLES.includes(k)) problems.push(`colour ${k} has no rk_role in core/include/rekta.h`);
    return `  { 0x00000000u, ${ROLES.map((r) => rgba(theme[r])).join(', ')} }`;
  });
  const densities = ['comfortable', 'compact'].map((d) => `  { ${METRICS.map(([g, k]) => f(g === 'density' ? json.densities[d][k] : json[g][k])).join(', ')} }`);
  const durations = DURATIONS.map(([g, k]) => f(json[g][k])).join(', ');
  const defs = [];
  const t = json.typography;
  for (const [k, v] of Object.entries(t)) {
    if (k.startsWith('font-size-')) {
      const n = C(k.slice(10));
      if (typeof v === 'number') defs.push(`#define RK_TOK_SIZE_${n} ${f(v)}`, `#define RK_TOK_SIZE_${n}_MAX ${f(v)}`, `#define RK_TOK_SIZE_${n}_VW 0.0f`);
      else defs.push(`#define RK_TOK_SIZE_${n} ${f(v.min)}`, `#define RK_TOK_SIZE_${n}_MAX ${f(v.max)}`, `#define RK_TOK_SIZE_${n}_VW ${f(v.viewport)}`);
    } else if (k.startsWith('font-weight-')) defs.push(`#define RK_TOK_WEIGHT_${C(k.slice(12))} ${v}`);
    else if (k.startsWith('line-height-')) defs.push(`#define RK_TOK_LINE_${C(k.slice(12))} ${f(v)}`);
  }
  for (const [k, v] of Object.entries(json.motion)) {
    if (k.startsWith('ease-')) defs.push(`#define RK_TOK_EASE_${C(k.slice(5))} { ${v.map(f).join(', ')} }`);
    else if (!k.startsWith('duration-')) defs.push(`#define RK_TOK_${C(k)} ${f(v)}`);
  }
  for (const [k, v] of Object.entries(json.timing)) defs.push(`#define RK_TOK_TIMING_${C(k.replace(/^duration-/, ''))} ${f(v)}`);
  for (const [k, v] of Object.entries(json.breakpoint)) defs.push(`#define RK_TOK_${C(k)} ${f(v)}`);
  defs.push(`#define RK_TOK_TILE_UNIT_ULTRAWIDE ${f(json.size['tile-unit-ultrawide'])}`);
  const out = HEAD(`Rekta Design ${json.version} tokens for rekta-core`)
    + `#ifndef RK_TOKENS_H\n#define RK_TOKENS_H\n\n#define RK_TOKENS_VERSION "${json.version}"\n\n`
    + `/* [theme: light, dark][rk_role], 0xRRGGBBAA */\nstatic const rk_color rk_tok_colors[2][RK_ROLE_COUNT] = {\n${themes.join(',\n')}\n};\n\n`
    + `/* [density: comfortable, compact][rk_metric], logical px */\nstatic const float rk_tok_metrics[2][RK_METRIC_COUNT] = {\n${densities.join(',\n')}\n};\n\n`
    + `/* [rk_duration], ms; the first RK_TOK_MOTION_COUNT are motion (0 under reduced motion), the rest wall-clock timings */\n`
    + `#define RK_TOK_MOTION_COUNT ${MOTION_COUNT}\nstatic const float rk_tok_durations[RK_DURATION_COUNT] = { ${durations} };\n\n`
    + `/* Type sizes as min, max and the share of the hosting width that moves between them (_VW); fixed sizes have _VW 0. */\n`
    + `${defs.join('\n')}\n\n#endif\n`;
  return { out, problems };
}

// SVG path data to polylines in grid units. Arcs and curves become short segments: fine enough for 20 units drawn at
// up to 3× (a circle of radius 7 is 48 segments; the error stays under 0.05 px).
function flatten(d) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g) || [];
  const subs = [];
  let i = 0, cmd = '', x = 0, y = 0, sx = 0, sy = 0, cur = null, lastC = null;
  const num = () => +tokens[i++];
  const move = (nx, ny) => { cur = { closed: false, pts: [[nx, ny]] }; subs.push(cur); x = sx = nx; y = sy = ny; };
  const line = (nx, ny) => { cur.pts.push([nx, ny]); x = nx; y = ny; };
  const cubic = (x1, y1, x2, y2, ex, ey) => {
    const x0 = x, y0 = y;
    for (let k = 1; k <= 16; k += 1) {
      const t = k / 16, u = 1 - t;
      line(u * u * u * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * ex, u * u * u * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * ey);
    }
    lastC = [x2, y2];
  };
  const arc = (rx, ry, phi, large, sweep, ex, ey) => {
    // SVG 1.1 F.6.5: endpoint to centre parameterization.
    const x1 = x, y1 = y, p = (phi * Math.PI) / 180, cp = Math.cos(p), sp = Math.sin(p);
    const dx = (x1 - ex) / 2, dy = (y1 - ey) / 2, x1p = cp * dx + sp * dy, y1p = -sp * dx + cp * dy;
    rx = Math.abs(rx); ry = Math.abs(ry);
    const lam = (x1p * x1p) / (rx * rx) + (y1p * y1p) / (ry * ry);
    if (lam > 1) { rx *= Math.sqrt(lam); ry *= Math.sqrt(lam); }
    const num2 = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p, den = rx * rx * y1p * y1p + ry * ry * x1p * x1p;
    const co = (large === sweep ? -1 : 1) * Math.sqrt(Math.max(0, num2 / den));
    const cxp = (co * rx * y1p) / ry, cyp = (-co * ry * x1p) / rx;
    const cx = cp * cxp - sp * cyp + (x1 + ex) / 2, cy = sp * cxp + cp * cyp + (y1 + ey) / 2;
    const ang = (ux, uy, vx, vy) => Math.atan2(ux * vy - uy * vx, ux * vx + uy * vy);
    const t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry);
    let dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry);
    if (!sweep && dt > 0) dt -= 2 * Math.PI; else if (sweep && dt < 0) dt += 2 * Math.PI;
    const n = Math.max(2, Math.ceil(Math.abs(dt) / ((2 * Math.PI) / 48)));
    for (let k = 1; k <= n; k += 1) {
      const t = t1 + (dt * k) / n;
      if (k === n) line(ex, ey);
      else line(cx + rx * Math.cos(t) * cp - ry * Math.sin(t) * sp, cy + rx * Math.cos(t) * sp + ry * Math.sin(t) * cp);
    }
  };
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) cmd = tokens[i++];
    const rel = cmd === cmd.toLowerCase(), ox = rel ? x : 0, oy = rel ? y : 0;
    switch (cmd.toUpperCase()) {
      case 'M': move(ox + num(), oy + num()); cmd = rel ? 'l' : 'L'; lastC = null; break;
      case 'L': line(ox + num(), oy + num()); lastC = null; break;
      case 'H': line(ox + num(), y); lastC = null; break;
      case 'V': line(x, oy + num()); lastC = null; break;
      case 'C': { const a = [num(), num(), num(), num(), num(), num()]; cubic(ox + a[0], oy + a[1], ox + a[2], oy + a[3], ox + a[4], oy + a[5]); break; }
      case 'S': {
        const a = [num(), num(), num(), num()], r1 = lastC ? [2 * x - lastC[0], 2 * y - lastC[1]] : [x, y];
        cubic(r1[0], r1[1], ox + a[0], oy + a[1], ox + a[2], oy + a[3]); break;
      }
      case 'A': { const a = [num(), num(), num(), num(), num(), num(), num()]; arc(a[0], a[1], a[2], a[3], a[4], ox + a[5], oy + a[6]); lastC = null; break; }
      case 'Z': cur.closed = true; x = sx; y = sy; cur = { closed: false, pts: [[x, y]] }; subs.push(cur); lastC = null; break;
      default: throw new Error(`path command ${cmd} is not supported by the C target`);
    }
  }
  return subs.filter((s) => s.pts.length > 1 || s.closed).map((s) => {
    // A closed path ends where it started: drop the repeated point.
    const p = s.pts;
    if (s.closed && p.length > 2 && Math.abs(p[0][0] - p[p.length - 1][0]) < 1e-6 && Math.abs(p[0][1] - p[p.length - 1][1]) < 1e-6) p.pop();
    return s;
  }).filter((s) => s.pts.length > 1);
}

export function coreIcons(icons) {
  const points = [], contours = [], defs = [];
  for (const [name, icon] of Object.entries(icons).sort(([a], [b]) => (a < b ? -1 : 1))) {
    const first = contours.length;
    for (const s of icon.shapes) {
      const fill = s.attrs.fill && s.attrs.fill !== 'none' ? 1 : 0;
      let subs;
      if (s.tag === 'path') subs = flatten(s.attrs.d);
      else if (s.tag === 'circle') {
        const cx = +s.attrs.cx, cy = +s.attrs.cy, r = +s.attrs.r;
        subs = [{ closed: true, pts: Array.from({ length: 48 }, (_, k) => [cx + r * Math.cos((k * Math.PI) / 24), cy + r * Math.sin((k * Math.PI) / 24)]) }];
      } else throw new Error(`icon ${name}: <${s.tag}> is not supported by the C target`);
      for (const sub of subs) {
        contours.push(`{ ${points.length / 2}, ${sub.pts.length}, ${sub.closed ? 1 : 0}, ${fill} }`);
        for (const [px, py] of sub.pts) points.push(+px.toFixed(3), +py.toFixed(3));
      }
    }
    defs.push(`{ "${name}", ${first}, ${contours.length - first} }`);
  }
  const rows = [];
  for (let k = 0; k < points.length; k += 16) rows.push('  ' + points.slice(k, k + 16).map(f).join(', '));
  return HEAD('Rekta Design icons for rekta-core: every shape as polylines on the 20-unit grid, stroked 1.6 with butt ends and mitred corners unless filled')
    + `#ifndef RK_ICONS_H\n#define RK_ICONS_H\n\n#define RK_ICON_GRID 20.0f\n#define RK_ICON_STROKE 1.6f\n\n`
    + `typedef struct rk_icon_contour { uint16_t start, count; uint8_t closed, fill; } rk_icon_contour;\n`
    + `typedef struct rk_icon_def { const char *name; uint16_t first, count; } rk_icon_def;\n\n`
    + `static const float rk_icon_points[] = {\n${rows.join(',\n')}\n};\n\n`
    + `static const rk_icon_contour rk_icon_contours[] = {\n  ${contours.join(',\n  ')}\n};\n\n`
    + `/* sorted by name */\n#define RK_ICON_COUNT ${defs.length}\nstatic const rk_icon_def rk_icon_defs[RK_ICON_COUNT] = {\n  ${defs.join(',\n  ')}\n};\n\n#endif\n`;
}

// The fonts the core draws with: Barlow in the weights the text styles use, the same Latin glyphs as the web
// (core/fonts/barlow-WEIGHT.ttf, without hinting tables), as byte arrays.
export function coreFonts(dir) {
  const files = readdirSync(dir).filter((x) => /^barlow-\d+\.ttf$/.test(x)).sort();
  let out = HEAD('Barlow (SIL Open Font License, core/fonts/OFL.txt) for rekta-core') + '#ifndef RK_FONTS_H\n#define RK_FONTS_H\n\n';
  const list = [];
  for (const file of files) {
    const w = /(\d+)/.exec(file)[1], bytes = readFileSync(join(dir, file)), rows = [];
    for (let k = 0; k < bytes.length; k += 24) rows.push(Array.from(bytes.subarray(k, k + 24)).join(','));
    out += `static const unsigned char rk_font_barlow_${w}[${bytes.length}] = {\n${rows.join(',\n')}\n};\n\n`;
    list.push(`{ ${w}, rk_font_barlow_${w}, ${bytes.length} }`);
  }
  return out + `typedef struct rk_font_file { int weight; const unsigned char *data; int size; } rk_font_file;\n`
    + `#define RK_FONT_FILE_COUNT ${list.length}\nstatic const rk_font_file rk_font_files[RK_FONT_FILE_COUNT] = {\n  ${list.join(',\n  ')}\n};\n\n#endif\n`;
}
