static void p_button(void *d, struct wl_pointer *p, uint32_t s, uint32_t t, uint32_t button, uint32_t state) {
  (void)d; (void)p; (void)t;
  pointer_serial = s; serial = s;
  if (!pointer_win) return;
  bool down = state == WL_POINTER_BUTTON_STATE_PRESSED;
  if (button == 0x110 && down) {                                /* BTN_LEFT on our own edge: the compositor resizes */
    uint32_t edge = edge_at(pointer_win, px, py);
    if (edge != XDG_TOPLEVEL_RESIZE_EDGE_NONE) { xdg_toplevel_resize(pointer_win->top, seat, s, edge); return; }
  }
  if (button == 0x113 || button == 0x116) {                     /* BTN_SIDE, BTN_BACK */
    if (!down) return;
    rk_event e;
    memset(&e, 0, sizeof e);
    e.size = sizeof e; e.type = RK_EVENT_KEY_DOWN; e.time = rk_app_now(); e.key = RK_KEY_BACK;
    rk__window_event(pointer_win->w, &e);
    return;
  }
  int b = button == 0x110 ? 0 : button == 0x111 ? 1 : button == 0x112 ? 2 : -1;
  if (b >= 0) send(down ? RK_EVENT_POINTER_DOWN : RK_EVENT_POINTER_UP, b);
}
