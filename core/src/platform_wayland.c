static uint32_t edge_at(wwin *x, float ex, float ey) {
  if (!x->own_frame || x->maximized) return XDG_TOPLEVEL_RESIZE_EDGE_NONE;
  bool L = ex < EDGE, R = ex >= x->lw - EDGE, T = ey < EDGE, B = ey >= x->lh - EDGE;
  if (T) return L ? XDG_TOPLEVEL_RESIZE_EDGE_TOP_LEFT : R ? XDG_TOPLEVEL_RESIZE_EDGE_TOP_RIGHT : XDG_TOPLEVEL_RESIZE_EDGE_TOP;
  if (B) return L ? XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM_LEFT : R ? XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM_RIGHT : XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM;
  if (L) return XDG_TOPLEVEL_RESIZE_EDGE_LEFT;
  if (R) return XDG_TOPLEVEL_RESIZE_EDGE_RIGHT;
  return XDG_TOPLEVEL_RESIZE_EDGE_NONE;
}

static void set_cursor(uint32_t edge) {
  int shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_DEFAULT;
  switch (edge) {
    case XDG_TOPLEVEL_RESIZE_EDGE_TOP: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_N_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_S_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_LEFT: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_W_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_RIGHT: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_E_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_TOP_LEFT: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_NW_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_TOP_RIGHT: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_NE_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM_LEFT: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_SW_RESIZE; break;
    case XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM_RIGHT: shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_SE_RESIZE; break;
    default:
      if (pointer_win && pointer_win->cursor == RK__CURSOR_TEXT) shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_TEXT;
      if (pointer_win && pointer_win->cursor == RK__CURSOR_COL_RESIZE) shape = WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_COL_RESIZE;
      break;
  }
  if (shape == cursor_shape) return;
  cursor_shape = shape;
  if (shape_dev) { wp_cursor_shape_device_v1_set_shape(shape_dev, pointer_serial, (uint32_t)shape); return; }
  /* an older compositor: the themed arrow, I-beam or column edge (the window's edges only through cursor-shape) */
  if (!cursor_theme) cursor_theme = wl_cursor_theme_load(getenv("XCURSOR_THEME"), 24, shm);
  const char *name = shape == WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_TEXT ? "xterm" : shape == WP_CURSOR_SHAPE_DEVICE_V1_SHAPE_COL_RESIZE ? "sb_h_double_arrow" : "left_ptr";
  struct wl_cursor *c = cursor_theme ? wl_cursor_theme_get_cursor(cursor_theme, name) : NULL;
  if (!c && cursor_theme) c = wl_cursor_theme_get_cursor(cursor_theme, "left_ptr");
  if (!c) c = cursor_theme ? wl_cursor_theme_get_cursor(cursor_theme, "default") : NULL;
  if (!c || !c->image_count) return;
  struct wl_cursor_image *img = c->images[0];
  if (!cursor_surface) cursor_surface = wl_compositor_create_surface(compositor);
  wl_pointer_set_cursor(pointer, pointer_serial, cursor_surface, (int32_t)img->hotspot_x, (int32_t)img->hotspot_y);
  wl_surface_attach(cursor_surface, wl_cursor_image_get_buffer(img), 0, 0);
  wl_surface_damage(cursor_surface, 0, 0, (int32_t)img->width, (int32_t)img->height);
  wl_surface_commit(cursor_surface);
}

static void wl_cursor(void *n, int shape) {
  wwin *x = n;
  if (!x) return;
  x->cursor = shape;
  if (pointer_win == x) set_cursor(edge_at(x, px, py));
}

static uint32_t mods_now(void) {
  if (!kstate) return 0;
  return (xkb_state_mod_name_is_active(kstate, XKB_MOD_NAME_SHIFT, XKB_STATE_MODS_EFFECTIVE) > 0 ? RK_MOD_SHIFT : 0) |
         (xkb_state_mod_name_is_active(kstate, XKB_MOD_NAME_CTRL, XKB_STATE_MODS_EFFECTIVE) > 0 ? RK_MOD_CTRL : 0) |
         (xkb_state_mod_name_is_active(kstate, XKB_MOD_NAME_ALT, XKB_STATE_MODS_EFFECTIVE) > 0 ? RK_MOD_ALT : 0) |
         (xkb_state_mod_name_is_active(kstate, XKB_MOD_NAME_LOGO, XKB_STATE_MODS_EFFECTIVE) > 0 ? RK_MOD_SUPER : 0);
}

static void send(rk_event_type type, int button) {
  if (!pointer_win) return;
  rk_event e;
  memset(&e, 0, sizeof e);
  e.size = sizeof e; e.type = type; e.time = rk_app_now(); e.button = button; e.mods = mods_now();
  e.position = (rk_point){ px, py };
  rk__window_event(pointer_win->w, &e);
}

