static bool wl_init(const rk_app_desc *d) {
  wdpy = wl_display_connect(NULL);
  if (!wdpy) return false;
  if (d && d->id && *d->id) app_id = d->id;
  registry = wl_display_get_registry(wdpy);
  wl_registry_add_listener(registry, &registry_listener, NULL);
  wl_display_roundtrip(wdpy);
  if (!compositor || !shm || !wm_base) { wl_display_disconnect(wdpy); wdpy = NULL; return false; }
  xkb = xkb_context_new(XKB_CONTEXT_NO_FLAGS);
  const char *locale = getenv("LC_ALL");
  if (!locale || !*locale) locale = getenv("LC_CTYPE");
  if (!locale || !*locale) locale = getenv("LANG");
  if (!locale || !*locale) locale = "C";
  if (xkb) ctable = xkb_compose_table_new_from_locale(xkb, locale, XKB_COMPOSE_COMPILE_NO_FLAGS);
  if (ctable) cstate = xkb_compose_state_new(ctable, XKB_COMPOSE_STATE_NO_FLAGS);
  wl_display_roundtrip(wdpy);                                    /* the seat's capabilities, the keymap */
  if (ti_mgr && seat) { ti = zwp_text_input_manager_v3_get_text_input(ti_mgr, seat); zwp_text_input_v3_add_listener(ti, &ti_listener, NULL); }
  if (data_mgr && seat) { data_dev = wl_data_device_manager_get_data_device(data_mgr, seat); wl_data_device_add_listener(data_dev, &dd_listener, NULL); }
  if (pipe(wpipe) == 0) { fcntl(wpipe[0], F_SETFL, O_NONBLOCK); fcntl(wpipe[1], F_SETFL, O_NONBLOCK); }
  return true;
}

static void wl_shutdown(void) {
  if (!wdpy) return;
  if (cursor_theme) wl_cursor_theme_destroy(cursor_theme);
  if (cursor_surface) wl_surface_destroy(cursor_surface);
  if (kstate) xkb_state_unref(kstate);
  if (keymap) xkb_keymap_unref(keymap);
  if (cstate) xkb_compose_state_unref(cstate);
  if (ctable) xkb_compose_table_unref(ctable);
  cstate = NULL; ctable = NULL;
  if (xkb) xkb_context_unref(xkb);
  if (shape_dev) wp_cursor_shape_device_v1_destroy(shape_dev);
  if (pointer) wl_pointer_destroy(pointer);
  if (keyboard) wl_keyboard_destroy(keyboard);
  if (seat) wl_seat_destroy(seat);
  if (shape_mgr) wp_cursor_shape_manager_v1_destroy(shape_mgr);
  if (ti) zwp_text_input_v3_destroy(ti);
  if (ti_mgr) zwp_text_input_manager_v3_destroy(ti_mgr);
  ti = NULL; ti_mgr = NULL; ti_on = false;
  free(ti_preedit); free(ti_commit); ti_preedit = ti_commit = NULL;
  offer_free(selection); selection = NULL;
  if (own_source) { wl_data_source_destroy(own_source); own_source = NULL; }
  free(own_text); own_text = NULL;
  if (data_dev) wl_data_device_destroy(data_dev);
  if (data_mgr) wl_data_device_manager_destroy(data_mgr);
  if (viewporter) wp_viewporter_destroy(viewporter);
  if (frac_mgr) wp_fractional_scale_manager_v1_destroy(frac_mgr);
  if (deco_mgr) zxdg_decoration_manager_v1_destroy(deco_mgr);
  xdg_wm_base_destroy(wm_base);
  wl_shm_destroy(shm);
  wl_compositor_destroy(compositor);
  wl_registry_destroy(registry);
  wl_display_disconnect(wdpy);
  wdpy = NULL;
  if (wpipe[0] >= 0) { close(wpipe[0]); close(wpipe[1]); wpipe[0] = wpipe[1] = -1; }
}

/* The loop's wait: Wayland's read protocol around poll, the wake pipe, and key repeat as a deadline. */
static bool wl_wait(double ms) {
  while (wl_display_prepare_read(wdpy) != 0) wl_display_dispatch_pending(wdpy);
  wl_display_flush(wdpy);
  if (repeat_key) { double left = repeat_next - wl_now(); ms = ms < 0 ? RK_MAX(0.0, left) : RK_MIN(ms, RK_MAX(0.0, left)); }
  struct pollfd fds[2] = { { wl_display_get_fd(wdpy), POLLIN, 0 }, { wpipe[0], POLLIN, 0 } };
  int n = poll(fds, wpipe[0] >= 0 ? 2 : 1, ms < 0 ? -1 : (int)ceil(ms));
  if (n > 0 && (fds[0].revents & POLLIN)) wl_display_read_events(wdpy); else wl_display_cancel_read(wdpy);
  if (wpipe[0] >= 0 && (fds[1].revents & POLLIN)) { char b[64]; while (read(wpipe[0], b, sizeof b) > 0) {} }
  if (wl_display_dispatch_pending(wdpy) < 0) { fprintf(stderr, "rekta: the Wayland compositor went away\n"); rk_app_quit(1); return false; }
  configures();
  if (repeat_key && wl_now() >= repeat_next) { key_event(repeat_key, true); repeat_next = wl_now() + 1000.0 / repeat_rate; }
  return true;
}

static void wl_wake(void) { if (wpipe[1] >= 0) { char c = 1; if (write(wpipe[1], &c, 1) < 0) {} } }

/* No XSETTINGS on Wayland: the theme and the animation setting come from GNOME's or KDE's settings. */
static bool line_has(const char *path, const char *key, const char *needle) {
  FILE *f = fopen(path, "r");
  if (!f) return false;
  char line[512];
  bool hit = false;
  while (fgets(line, sizeof line, f)) if (!strncmp(line, key, strlen(key)) && strstr(line, needle)) { hit = true; break; }
  fclose(f);
  return hit;
}

static void wl_settings(bool *dark, bool *reduced, bool *compact) {
  *dark = false; *reduced = false; *compact = true;
  const char *gt = getenv("GTK_THEME");
  if (gt && (strstr(gt, ":dark") || strstr(gt, "-dark") || strstr(gt, "-Dark"))) *dark = true;
  const char *home = getenv("HOME");
  char path[1024];
  if (home) {
    snprintf(path, sizeof path, "%s/.config/kdeglobals", home);
    if (line_has(path, "ColorScheme=", "Dark")) *dark = true;
    if (line_has(path, "AnimationDurationFactor=", "=0\n")) *reduced = true;
  }
  FILE *p = popen("gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null; gsettings get org.gnome.desktop.interface enable-animations 2>/dev/null", "r");
  if (p) {
    char line[128];
    while (fgets(line, sizeof line, p)) { if (strstr(line, "prefer-dark")) *dark = true; if (!strncmp(line, "false", 5)) *reduced = true; }
    pclose(p);
  }
}

/* The compositor paces the frames: a window is drawn when its last frame has been shown (its frame callback came). */
static bool wl_ready(void *n) { wwin *x = n; return x && x->configured && !x->frame_pending; }

/* A floating window may choose its own size: the next commit carries it. */
static void wl_resize(void *n, float w, float h) {
  wwin *x = n;
  if (!x || x->maximized) return;
  x->fw = x->lw = (int)lroundf(w); x->fh = x->lh = (int)lroundf(h);
  apply_size(x);
}

