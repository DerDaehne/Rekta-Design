/* Keyboard ------------------------------------------------------------------------------------------------------ */

static uint32_t wkey_of(xkb_keysym_t s) {
  switch (s) {
    case XKB_KEY_Tab: case XKB_KEY_ISO_Left_Tab: return RK_KEY_TAB;
    case XKB_KEY_Return: case XKB_KEY_KP_Enter: return RK_KEY_ENTER;
    case XKB_KEY_Escape: return RK_KEY_ESCAPE;
    case XKB_KEY_space: return RK_KEY_SPACE;
    case XKB_KEY_Left: return RK_KEY_LEFT; case XKB_KEY_Right: return RK_KEY_RIGHT; case XKB_KEY_Up: return RK_KEY_UP; case XKB_KEY_Down: return RK_KEY_DOWN;
    case XKB_KEY_Home: return RK_KEY_HOME; case XKB_KEY_End: return RK_KEY_END; case XKB_KEY_Prior: return RK_KEY_PAGE_UP; case XKB_KEY_Next: return RK_KEY_PAGE_DOWN;
    case XKB_KEY_BackSpace: return RK_KEY_BACKSPACE; case XKB_KEY_Delete: return RK_KEY_DELETE;
    case XKB_KEY_XF86Back: return RK_KEY_BACK;
    default: break;
  }
  if (s >= XKB_KEY_F1 && s <= XKB_KEY_F10) return RK_KEY_F1 + (s - XKB_KEY_F1);
  if (s >= XKB_KEY_a && s <= XKB_KEY_z) return 'A' + (s - XKB_KEY_a);
  if ((s >= XKB_KEY_A && s <= XKB_KEY_Z) || (s >= XKB_KEY_0 && s <= XKB_KEY_9)) return s;
  if (s > 0x20 && s < 0x7f) return s;
  return RK_KEY_NONE;
}

/* Dead keys and the Compose key, as the locale's compose table says: the keys of a sequence type nothing until it is
   complete (´ then e: é), and a sequence that goes nowhere types nothing. */
static bool composed(xkb_keysym_t sym, char *text, size_t size) {
  text[0] = 0;
  if (!cstate || xkb_compose_state_feed(cstate, sym) != XKB_COMPOSE_FEED_ACCEPTED) return false;
  switch (xkb_compose_state_get_status(cstate)) {
    case XKB_COMPOSE_COMPOSING: return true;
    case XKB_COMPOSE_COMPOSED: xkb_compose_state_get_utf8(cstate, text, size); xkb_compose_state_reset(cstate); return true;
    case XKB_COMPOSE_CANCELLED: xkb_compose_state_reset(cstate); return true;
    default: return false;
  }
}

static void key_event(uint32_t code, bool down) {
  if (!key_win || !kstate) return;
  xkb_keysym_t sym = xkb_state_key_get_one_sym(kstate, code);
  rk_event e;
  memset(&e, 0, sizeof e);
  e.size = sizeof e; e.type = down ? RK_EVENT_KEY_DOWN : RK_EVENT_KEY_UP; e.time = rk_app_now();
  e.key = wkey_of(sym); e.mods = mods_now();
  char done[64];
  if (down && !(e.mods & (RK_MOD_CTRL | RK_MOD_SUPER)) && composed(sym, done, sizeof done)) {
    if (done[0]) { e.type = RK_EVENT_TEXT; e.key = 0; e.text = done; rk__window_event(key_win->w, &e); }
    return;
  }
  if (e.key) rk__window_event(key_win->w, &e);
  if (!down || (e.mods & (RK_MOD_CTRL | RK_MOD_SUPER))) return;
  char text[64];
  int n = xkb_state_key_get_utf8(kstate, code, text, sizeof text);
  if (n > 0 && (unsigned char)text[0] >= 0x20 && text[0] != 0x7f) {
    rk_event t = e;
    t.type = RK_EVENT_TEXT; t.key = 0; t.text = text;
    rk__window_event(key_win->w, &t);
  }
}

static void k_keymap(void *d, struct wl_keyboard *k, uint32_t format, int32_t fd, uint32_t size) {
  (void)d; (void)k;
  if (format != WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1) { close(fd); return; }
  char *map = mmap(NULL, size, PROT_READ, MAP_PRIVATE, fd, 0);
  close(fd);
  if (map == MAP_FAILED) return;
  struct xkb_keymap *km = xkb_keymap_new_from_string(xkb, map, XKB_KEYMAP_FORMAT_TEXT_V1, XKB_KEYMAP_COMPILE_NO_FLAGS);
  munmap(map, size);
  if (!km) return;
  if (kstate) xkb_state_unref(kstate);
  if (keymap) xkb_keymap_unref(keymap);
  keymap = km; kstate = xkb_state_new(km);
}
static void k_enter(void *d, struct wl_keyboard *k, uint32_t s, struct wl_surface *surf, struct wl_array *keys) { (void)d; (void)k; (void)keys; serial = s; key_win = wfind(surf); }
static void k_leave(void *d, struct wl_keyboard *k, uint32_t s, struct wl_surface *surf) { (void)d; (void)k; (void)s; (void)surf; key_win = NULL; repeat_key = 0; }
static void k_key(void *d, struct wl_keyboard *k, uint32_t s, uint32_t t, uint32_t key, uint32_t state) {
  (void)d; (void)k; (void)t;
  serial = s;
  uint32_t code = key + 8;
  bool down = state == WL_KEYBOARD_KEY_STATE_PRESSED;
  key_event(code, down);
  if (down && keymap && xkb_keymap_key_repeats(keymap, code) && repeat_rate > 0) { repeat_key = code; repeat_next = wl_now() + repeat_delay; }
  else if (!down && repeat_key == code) repeat_key = 0;
}
static void k_mods(void *d, struct wl_keyboard *k, uint32_t s, uint32_t dep, uint32_t lat, uint32_t lock, uint32_t group) {
  (void)d; (void)k; (void)s;
  if (kstate) xkb_state_update_mask(kstate, dep, lat, lock, 0, 0, group);
}
static void k_repeat(void *d, struct wl_keyboard *k, int32_t rate, int32_t delay) { (void)d; (void)k; repeat_rate = rate; repeat_delay = delay; }
static const struct wl_keyboard_listener keyboard_listener = { k_keymap, k_enter, k_leave, k_key, k_mods, k_repeat };

